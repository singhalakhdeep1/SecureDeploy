import { BadRequestException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import type { ComplianceFramework, ComplianceReport, Finding } from '@prisma/client';
import { PrismaService } from '../../common/prisma/prisma.service';
import { StructuredLoggingService } from '../../common/services/structured-logging/structured-logging.service';
import type { AuthUser } from '../../common/auth/decorators';
import { ComplianceService } from '../compliance/compliance.service';
import { FRAMEWORKS } from '../compliance/catalog';
import type { GenerateReportDto } from './dto/report.dto';

type ControlRow = Awaited<ReturnType<ComplianceService['getControls']>>[number];

@Injectable()
export class ReportingService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly compliance: ComplianceService,
    private readonly logging: StructuredLoggingService,
  ) {}

  /**
   * Builds a compliance report for a framework and time window: findings first seen in the window
   * that map to the framework, current control status, executive summary. The PDF is stored with
   * the report row and served by /reporting/download/:id.
   */
  async generateReport(dto: GenerateReportDto, user: AuthUser) {
    if (user.role === 'DEVELOPER') throw new ForbiddenException('Reports are generated by security leads, admins and auditors');
    const framework = dto.framework.toUpperCase() as ComplianceFramework;
    if (!FRAMEWORKS.some((f) => f.id === framework)) throw new BadRequestException(`Unknown framework ${dto.framework}`);
    const startDate = new Date(dto.startDate);
    const endDate = new Date(dto.endDate);
    if (Number.isNaN(startDate.getTime()) || Number.isNaN(endDate.getTime()) || startDate > endDate) throw new BadRequestException('Invalid date range');
    endDate.setUTCHours(23, 59, 59, 999);

    const findings = await this.prisma.finding.findMany({
      where: {
        firstSeenAt: { gte: startDate, lte: endDate },
        complianceMappings: { some: { framework } },
        ...(dto.service ? { service: dto.service } : {}),
      },
      include: { complianceMappings: { where: { framework } } },
      orderBy: [{ severity: 'asc' }, { firstSeenAt: 'asc' }],
    });
    const controls = await this.compliance.getControls(framework, dto.service);
    const resolvedCount = findings.filter((f) => f.status === 'RESOLVED').length;
    const complianceScore = Math.round((controls.filter((c) => c.compliant).length / controls.length) * 1000) / 10;

    const report = await this.prisma.complianceReport.create({
      data: {
        title: `${FRAMEWORKS.find((f) => f.id === framework)!.name} Compliance Report${dto.service ? ` - ${dto.service}` : ''}`,
        framework,
        startDate,
        endDate,
        generatedBy: user.email,
        findingsCount: findings.length,
        resolvedCount,
        criticalCount: findings.filter((f) => f.severity === 'CRITICAL').length,
        highCount: findings.filter((f) => f.severity === 'HIGH').length,
        complianceScore,
      },
    });
    const pdf = await this.renderPdf(report, findings, controls, dto.service);
    const stored = await this.prisma.complianceReport.update({
      where: { id: report.id },
      data: { pdf, pdfUrl: `/api/reporting/download/${report.id}` },
      select: { id: true, title: true, framework: true, complianceScore: true, pdfUrl: true, findingsCount: true, generatedAt: true },
    });
    await this.logging.logAuditEvent('report.generated', `${report.title} (${dto.startDate}..${dto.endDate})`, { entityType: 'report', entityId: report.id, complianceScore });
    return { reportId: stored.id, ...stored, sizeBytes: pdf.length };
  }

  private renderPdf(report: ComplianceReport, findings: (Finding & { complianceMappings: { controlId: string }[] })[], controls: ControlRow[], service?: string): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 50, size: 'A4', info: { Title: report.title, Author: 'SecureDeploy' } });
      const chunks: Buffer[] = [];
      doc.on('data', (c: Buffer) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const day = (d: Date) => d.toISOString().slice(0, 10);
      doc.fontSize(18).text(report.title, { align: 'center' }).moveDown(0.5);
      doc.fontSize(10).fillColor('#555').text(`Period ${day(report.startDate)} to ${day(report.endDate)}${service ? `  |  Service ${service}` : ''}  |  Generated ${report.generatedAt.toISOString()} by ${report.generatedBy}`, { align: 'center' });
      doc.fillColor('#000').moveDown();

      doc.fontSize(14).text('Executive summary').moveDown(0.3);
      const compliant = controls.filter((c) => c.compliant).length;
      doc.fontSize(11)
        .text(`Compliance score: ${report.complianceScore.toFixed(1)}% (${compliant} of ${controls.length} controls without open findings)`)
        .text(`Findings in period: ${report.findingsCount}  (resolved ${report.resolvedCount}, critical ${report.criticalCount}, high ${report.highCount})`)
        .text(
          report.criticalCount > 0
            ? 'Critical findings were reported in this period; deployments of affected services are gated until they are resolved or excepted.'
            : 'No critical findings were reported in this period.',
        )
        .moveDown();

      doc.fontSize(14).text('Control status').moveDown(0.3);
      for (const c of controls) {
        doc.fontSize(10).fillColor(c.compliant ? '#1a7f37' : '#c62828').text(`${c.compliant ? 'PASS' : 'FAIL'}  `, { continued: true })
          .fillColor('#000').text(`${c.clause} ${c.title}${c.compliant ? '' : ` - ${c.openFindings} open finding(s), max risk ${c.maxRiskScore}`}`);
      }
      doc.moveDown();

      doc.fontSize(14).text('Findings').moveDown(0.3);
      if (findings.length === 0) doc.fontSize(10).text('No mapped findings in this period.');
      findings.slice(0, 500).forEach((f, i) => {
        doc.fontSize(10).text(`${i + 1}. [${f.severity}] ${f.title}`, { continued: false });
        doc.fontSize(9).fillColor('#444').text(
          `   ${f.service}/${f.environment}  |  ${f.tool}  |  status ${f.status}${f.resolvedAt ? ` (resolved ${day(f.resolvedAt)})` : ''}  |  controls ${f.complianceMappings.map((m) => m.controlId).join(', ')}`,
        ).fillColor('#000');
      });
      if (findings.length > 500) doc.moveDown().fontSize(9).text(`... ${findings.length - 500} more findings omitted.`);
      doc.end();
    });
  }

  async downloadReport(id: string) {
    const report = await this.prisma.complianceReport.findUnique({ where: { id }, select: { title: true, pdf: true, generatedAt: true } });
    if (!report?.pdf) throw new NotFoundException('Report not found');
    return report;
  }

  getHistory(framework?: string) {
    return this.prisma.complianceReport.findMany({
      where: framework ? { framework: framework.toUpperCase() as ComplianceFramework } : {},
      orderBy: { generatedAt: 'desc' },
      take: 50,
      select: { id: true, title: true, framework: true, startDate: true, endDate: true, generatedBy: true, generatedAt: true, findingsCount: true, resolvedCount: true, criticalCount: true, highCount: true, complianceScore: true, pdfUrl: true },
    });
  }
}
